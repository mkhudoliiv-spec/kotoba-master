// Yōon like きゃ fall back to the note of their first (big) kana
export function getGlyphNote(char) {
  return KANA_NOTES[char] || KANJI_NOTES[char] || ([...char].length > 1 ? KANA_NOTES[[...char][0]] : null) || null;
}

export function hasGlyphNote(char) {
  return Boolean(getGlyphNote(char));
}
